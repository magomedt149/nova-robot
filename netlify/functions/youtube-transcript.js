function json(statusCode, payload) {
  return {
    statusCode,
    headers: {
      'Content-Type': 'application/json; charset=utf-8',
      'Cache-Control': 'no-store',
      'Access-Control-Allow-Origin': '*'
    },
    body: JSON.stringify(payload)
  };
}

function getVideoId(input) {
  const value = String(input || '').trim();
  if (/^[\w-]{11}$/.test(value)) return value;
  try {
    const url = new URL(value);
    if (url.hostname === 'youtu.be') return url.pathname.split('/').filter(Boolean)[0] || '';
    if (url.hostname.includes('youtube.com')) {
      if (url.pathname === '/watch') return url.searchParams.get('v') || '';
      const parts = url.pathname.split('/').filter(Boolean);
      const marker = parts.findIndex((p) => ['shorts', 'embed', 'live'].includes(p));
      if (marker >= 0 && parts[marker + 1]) return parts[marker + 1];
    }
  } catch (_) {}
  return '';
}

function decodeHtml(text) {
  return String(text || '')
    .replace(/&amp;/g, '&')
    .replace(/&quot;/g, '"')
    .replace(/&#39;/g, "'")
    .replace(/&lt;/g, '<')
    .replace(/&gt;/g, '>');
}

exports.handler = async (event) => {
  if (event.httpMethod === 'OPTIONS') return { statusCode: 204, headers: { 'Access-Control-Allow-Origin': '*' } };
  try {
    const body = event.body ? JSON.parse(event.body) : {};
    const input = body.url || event.queryStringParameters?.url || '';
    const videoId = getVideoId(input);
    if (!videoId) return json(400, { ok: false, error: 'Неверная ссылка YouTube.' });

    const watchUrl = `https://www.youtube.com/watch?v=${encodeURIComponent(videoId)}&hl=en`;
    const watch = await fetch(watchUrl, {
      headers: {
        'User-Agent': 'Mozilla/5.0 (iPhone; CPU iPhone OS 18_0 like Mac OS X) AppleWebKit/605.1.15 Version/18.0 Mobile/15E148 Safari/604.1',
        'Accept-Language': 'en-US,en;q=0.9'
      }
    });
    if (!watch.ok) throw new Error(`YouTube HTTP ${watch.status}`);
    const html = await watch.text();

    const captionMatch = html.match(/"captionTracks":(\[.*?\])/);
    if (!captionMatch) {
      return json(404, { ok: false, error: 'У этого видео нет доступных субтитров или YouTube не разрешил получить расшифровку.' });
    }

    let tracks;
    try { tracks = JSON.parse(captionMatch[1]); }
    catch (_) { return json(500, { ok: false, error: 'Не удалось разобрать список субтитров YouTube.' }); }
    if (!Array.isArray(tracks) || !tracks.length) return json(404, { ok: false, error: 'Субтитры не найдены.' });

    const preferred = tracks.find((t) => String(t.languageCode || '').toLowerCase().startsWith('en')) || tracks[0];
    const captionUrl = `${preferred.baseUrl}${preferred.baseUrl.includes('?') ? '&' : '?'}fmt=json3`;
    const captions = await fetch(captionUrl, { headers: { 'User-Agent': 'Mozilla/5.0' } });
    if (!captions.ok) throw new Error(`Captions HTTP ${captions.status}`);
    const data = await captions.json();

    const pieces = [];
    for (const ev of data.events || []) {
      if (!ev.segs) continue;
      const text = ev.segs.map((s) => s.utf8 || '').join('');
      if (text.trim()) pieces.push(text.trim());
    }
    const transcript = pieces.join(' ').replace(/\s+/g, ' ').trim();
    if (!transcript) return json(404, { ok: false, error: 'Расшифровка оказалась пустой.' });

    const titleMatch = html.match(/<title>(.*?)<\/title>/i);
    const title = decodeHtml(titleMatch?.[1] || '').replace(/\s*-\s*YouTube\s*$/i, '').trim();
    return json(200, {
      ok: true,
      videoId,
      title,
      language: preferred.languageCode || '',
      trackName: preferred.name?.simpleText || '',
      isAutoGenerated: preferred.kind === 'asr',
      transcript
    });
  } catch (error) {
    return json(500, { ok: false, error: error?.message || 'Ошибка получения YouTube-расшифровки.' });
  }
};
